"""Reeb interior door data -> src/model/reebData.ts.

reeb-dims.json: rows from Reeb's Interior Stile & Rail In-Stock Dimensions sheets (primed and wood,
files.reeb.com, v2.1): style, height, species, 3'0" stile, top rail, lock rail, bottom rail, panel, vendor.
reeb-prices.json: door-only and single-unit (prehung) prices for 1-3/8" doors from Reeb's interior price
catalog (reeb.cld.bz, effective 8/10/26), from scripts/parse_reeb_prices.py. Only standard widths 2/0-3/0
whose prices rise with width are kept, since the catalog text doesn't always come out in table order.

Usage: python3 scripts/import-reeb.py data/reeb/reeb-dims.json data/reeb/reeb-prices.json
"""
import json, re, sys

def inch(s):
    s = s.replace('"', '').replace('”', '').replace("'", '').strip()
    if not s or s.upper() == 'N/A': return None
    # Reeb's sheet has a few sizes a spreadsheet turned into dates: 4/5/2016 is 4-5/16"
    m = re.fullmatch(r'(\d+)/(\d+)/20(\d\d)', s)
    if m: s = f'{m.group(1)}-{m.group(2)}/{m.group(3)}'
    tot = 0.0
    for part in re.split(r'[- ]', s):
        if '/' in part:
            a, b = part.split('/'); tot += int(a) / int(b)
        elif part: tot += float(part)
    return round(tot, 4)

dims = {}
for line, code, height, species, stile, top, lock, bottom, panel, vendor in json.load(open(sys.argv[1])):
    if code.startswith('DoorStyle'): continue
    thick = '1-3/4' if '1-3/4' in code else '1-3/8'
    if thick != '1-3/8' or 'Bifold' in code or 'Transom' in code or 'Sidelite' in code: continue
    c = re.sub(r'[\s*]', '', code).upper()
    dims.setdefault(c, {})[height] = {'stile': inch(stile), 'top': inch(top), 'lock': inch(lock), 'bottom': inch(bottom), 'panel': inch(panel), 'species': re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', species), 'vendor': vendor}

WIDTHS = ['2/0', '2/2', '2/4', '2/6', '2/8', '2/10', '3/0']
prices = {}
for code, hs in json.load(open(sys.argv[2])).items():
    for h, ws in hs.items():
        seq = [(w, ws[w]) for w in WIDTHS if w in ws and ws[w]['door'] and ws[w]['unit']]
        if len(seq) < 2: continue
        if any(b[1]['door'] < a[1]['door'] or b[1]['unit'] < a[1]['unit'] for a, b in zip(seq, seq[1:])): continue
        if any(v['unit'] - v['door'] < 40 or v['unit'] - v['door'] > 200 for _, v in seq): continue
        prices.setdefault(code.upper(), {})[h] = {w: [v['door'], v['unit']] for w, v in seq}

src = f"""// Generated by scripts/import-reeb.py. Reeb interior stile & rail in-stock dimensions (primed and
// wood sheets, v2.1) and 1-3/8" door prices from Reeb's interior price catalog effective 8/10/26.
export interface ReebDims {{ stile: number | null; top: number | null; lock: number | null; bottom: number | null; panel: number | null; species: string; vendor: string }}

/** By style code, then door height (6/8, 7/0, 8/0). */
export const reebDims: Record<string, Record<string, ReebDims>> = {json.dumps(dims, separators=(',', ':'))};

/** By style code, height, then width: [door only, prehung single unit]. */
export const reebPrices: Record<string, Record<string, Record<string, [number, number]>>> = {json.dumps(prices, separators=(',', ':'))};

export const reebPriceDate = '8/10/26';
"""
open('src/model/reebData.ts', 'w').write(src)
print(len(dims), 'styles with dimensions;', len(prices), 'with prices')
