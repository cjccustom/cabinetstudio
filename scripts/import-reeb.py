"""Reeb interior door data -> src/model/reebData.ts.

reeb-dims.json: rows from Reeb's Interior Stile & Rail In-Stock Dimensions sheets (primed and wood,
files.reeb.com, v2.1): style, height, species, 3'0" stile, top rail, lock rail, bottom rail, panel, vendor.

Usage: python3 scripts/import-reeb.py data/reeb/reeb-dims.json
"""
import json, re, sys

def inch(s):
    s = s.replace('"', '').replace('”', '').replace("'", '').strip()
    if not s or s.upper() == 'N/A': return None
    # Reeb's sheet has a few sizes a spreadsheet turned into dates: 4/5/2016 is 4-5/16"
    m = re.fullmatch(r'(\d+)/(\d+)/20(\d\d)', s)
    if m: s = f'{m.group(1)}-{m.group(2)}/{m.group(3)}'
    tot = 0.0
    for part in re.split(r'[- ]', s):
        if '/' in part:
            a, b = part.split('/'); tot += int(a) / int(b)
        elif part: tot += float(part)
    return round(tot, 4)

dims = {}
for line, code, height, species, stile, top, lock, bottom, panel, vendor in json.load(open(sys.argv[1])):
    if code.startswith('DoorStyle'): continue
    thick = '1-3/4' if '1-3/4' in code else '1-3/8'
    if thick != '1-3/8' or 'Bifold' in code or 'Transom' in code or 'Sidelite' in code: continue
    c = re.sub(r'[\s*]', '', code).upper()
    dims.setdefault(c, {})[height] = {'stile': inch(stile), 'top': inch(top), 'lock': inch(lock), 'bottom': inch(bottom), 'panel': inch(panel), 'species': re.sub(r'(?<=[a-z])(?=[A-Z])', ' ', species), 'vendor': vendor}

src = f"""// Generated by scripts/import-reeb.py from Reeb's interior stile & rail In-Stock Dimensions sheets
// (primed and wood, v2.1, files.reeb.com).
export interface ReebDims {{ stile: number | null; top: number | null; lock: number | null; bottom: number | null; panel: number | null; species: string; vendor: string }}

/** By style code, then door height (6/8, 7/0, 8/0). */
export const reebDims: Record<string, Record<string, ReebDims>> = {json.dumps(dims, separators=(',', ':'))};
"""
open('src/model/reebData.ts', 'w').write(src)
print(len(dims), 'styles with dimensions')
