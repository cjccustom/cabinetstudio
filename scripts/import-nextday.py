#!/usr/bin/env python3
"""Build src/model/nextDay.ts from the Next Day Moulding price list collected in Chrome (CSV).

Usage: python3 scripts/import-nextday.py path/to/ndm_ALL_price_list.csv
One profile per moulding, priced per lineal foot in each material it comes in; corbels separately.
"""
import csv, json, re, sys
from fractions import Fraction

SPECIES = {'Poplar': 'Poplar', 'Cherry': 'Cherry', 'Maple': 'Maple', 'Red oak': 'Red Oak', 'White oak': 'Whiteoak',
           'Pine': 'Pine', 'Primed finger-jointed pine': 'Primed FJ pine', 'Flexible rubber-resin': 'Flex',
           'Flexible (oak-grain)': 'Flex', 'PVC': 'PVC', 'not stated': 'Paint grade'}
CATEGORY = {'Crown': 'Crown', 'Casing': 'Window and Door Casing', 'Base': 'Base Board and Base Cap', 'Base cap': 'Base Board and Base Cap',
            'Base cap / Panel': 'Panel', 'Shoe / Quarter round': 'Shoe Moulding', 'Cove / Scotia': 'Scotia', 'Chair rail': 'Chair Rail'}
MAT = r'(-PFJ|-WHITEOAK|-PINE|-POP|POP|PINE|CHE|RO|MAP|MPL|WO|PVC)'

def inches(s):
    """'1-3/8', '4-5/8 (face)', '9/16', '5' to inches; None when missing."""
    m = re.match(r'\s*(\d+)?(?:[- ](\d+/\d+))?|\s*(\d+/\d+)', s or '')
    s = (s or '').strip()
    m = re.match(r'^(\d+)-(\d+/\d+)', s) or re.match(r'^(\d+/\d+)', s) or re.match(r'^(\d+(?:\.\d+)?)', s)
    if not m: return None
    if len(m.groups()) == 2: return float(int(m.group(1)) + Fraction(m.group(2)))
    g = m.group(1)
    return float(Fraction(g)) if '/' in g else float(g)

def per_foot(row):
    price = float(row['Price'])
    per = row['Price per'].strip()
    if per == 'foot': return price
    if per == 'piece':
        m = re.match(r'(\d+) ft', row['Lengths'])
        if m: return price / int(m.group(1))
    return None

rows = list(csv.DictReader(open(sys.argv[1], encoding='utf-8'), skipinitialspace=True))
profiles, corbels = {}, []
for r in rows:
    r = {k.strip(): (v or '').strip() for k, v in r.items()}
    if r['Category'] == 'Corbel':
        corbels.append({'code': r['Item number'], 'name': r['Name'].title(), 'w': inches(r['Width']), 'h': inches(r['Height']), 'price': float(r['Price']), 'url': r['Page link']})
        continue
    cat = CATEGORY.get(r['Category'])
    if not cat: continue
    item = r['Item number']
    flex = item.startswith('FLEX-')
    base = item[5:] if flex else item
    if r['Price per'] == 'piece' and re.search(r'\d\d$', base) and re.match(r'\d+ ft$', r['Lengths']): base = base[:-2]
    base = re.sub(MAT + r'$', '', base) or base
    w, t = inches(r['Width']), inches(r['Thickness'])
    if not w or not t: continue
    key = f"{base}|{cat}|{w:.3f}|{t:.3f}"
    pf = per_foot(r)
    sp = SPECIES.get(r['Material'], r['Material'])
    p = profiles.setdefault(key, {'num': f'ND-{base}', 'code': base, 'supplier': 'nextday', 'category': cat, 't': round(t, 4), 'w': round(w, 4), 'prices': {}, 'name': '', 'url': r['Page link'], 'img': '' if r['Profile drawing link'] == 'none' else r['Profile drawing link'], 'lengths': set()})
    # The plain name: sizes and material wording dropped
    nm = re.sub(r'^[\d/ X-]+(FOOT|FT)?\s*', '', r['Name'], flags=re.I)
    nm = re.sub(r'\b(PFJ|PRIMED|SOLID|POPLAR|PINE|CHERRY|RED OAK|WHITE OAK|MAPLE|FLEX|PVC)\b\s*', '', nm, flags=re.I).strip().title()
    if not p['name'] or len(nm) < len(p['name']): p['name'] = nm or r['Category']
    if pf: p['prices'][sp] = round(min(pf, p['prices'].get(sp, 1e9)), 3)
    p['lengths'].add(r['Lengths'])
    if cat == 'Crown':
        m = re.search(r'\(([\d/ -]+) proj x ([\d/ -]+) drop\)', r['Crown angle'])
        if m and 'fit' not in p: p['fit'] = {'depth': inches(m.group(1)), 'height': inches(m.group(2))}

# Same code in two sizes: keep both, told apart by size
seen = {}
for p in profiles.values():
    seen.setdefault(p['num'], []).append(p)
for num, ps in seen.items():
    if len(ps) > 1:
        for p in ps: p['num'] = f"{num}-{p['w']:g}x{p['t']:g}"
out = []
for p in sorted(profiles.values(), key=lambda p: (p['category'], p['w'], p['code'])):
    p['lengths'] = ', '.join(sorted(p['lengths']))
    if not p['img']: del p['img']
    out.append(p)
src = f"""// Generated by scripts/import-nextday.py from Next Day Moulding's online prices (collected in Chrome,
// {len(rows)} rows). Prices are per lineal foot in each material, the lowest across the lengths sold
// (pieces sold by length are worked back to $/ft). No traced shapes yet: they draw from their sizes
// (crowns from their projection and drop) until the profile drawings are traced.
import type {{ AMProfile }} from './andersonMcquaid';

export interface NextDayProfile extends AMProfile {{ supplier: 'nextday'; code: string; name: string; url: string; img?: string; lengths: string; fit?: {{ depth: number; height: number }} }}
export interface NextDayCorbel {{ code: string; name: string; w: number | null; h: number | null; price: number; url: string }}

export const nextDayCatalog: NextDayProfile[] = {json.dumps(out, separators=(',', ':'))};

export const nextDayCorbels: NextDayCorbel[] = {json.dumps(corbels, separators=(',', ':'))};
"""
open('src/model/nextDay.ts', 'w').write(src)
print(len(out), 'profiles,', len(corbels), 'corbels')
from collections import Counter
print(Counter(p['category'] for p in out))
