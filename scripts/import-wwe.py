"""Turn a Woodworker Express price snapshot (JSON) into src/model/woodworkerExpress.ts.

Usage: python3 scripts/import-wwe.py data/woodworker-express-blum-YYYY-MM-DD.json
"""
import json, sys

src = sys.argv[1]
d = json.load(open(src))
keep = []
for p in d['products']:
    keep.append({
        'sku': p['supplier_sku'],
        'part': p['manufacturer_part_number'],
        'category': p['category'],
        'series': p['series'],
        'description': p['description'],
        'unit': p['unit'],
        'price': p['base_unit_price_usd'],
        'tiers': [{'min': t['minimum_quantity'], 'price': t['unit_price_usd']} for t in p['quantity_tiers']],
        **({'length': p['nominal_length_in']} if p['nominal_length_in'] else {}),
        **({'overlay': p['overlay_in']} if p['overlay_in'] else {}),
        **({'hand': p['handedness']} if p['handedness'] else {}),
        **({'sides': [p['drawer_side_min_in'], p['drawer_side_max_in']]} if p['drawer_side_min_in'] else {}),
        'url': p['source_url'],
    })
out = f"""// Generated by scripts/import-wwe.py from {src.split('/')[-1]}. Do not edit by hand.
// {d['catalog_name']}. {d['price_basis']}

export interface WWEPart {{
  sku: string;
  part: string;
  category: string;
  series: string;
  description: string;
  unit: string;
  price: number;
  tiers: {{ min: number; price: number }}[];
  length?: number;
  overlay?: number;
  hand?: string;
  sides?: [number, number];
  url: string;
}}

export const wwePriceDate = {json.dumps(d['price_checked_date'])};

export const wweParts: WWEPart[] = {json.dumps(keep, indent=1)};
"""
open('src/model/woodworkerExpress.ts', 'w').write(out)
print(len(keep), 'parts')
