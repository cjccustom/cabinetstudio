"""Turn shapes pulled from Brosco's stock moulding chart (BROSCO-Mldg-Chart.pdf, brosco.com) into
src/model/brosco.ts. Categories use the same names as the A&M catalog so both show in each picker.

Usage: python3 scripts/import-brosco.py profiles.json
"""
import json, re, sys

d = json.load(open(sys.argv[1]))
shapes, labels = d['shapes'], d['labels']

def category(name, heading):
    # The profile's own name first; the section heading only when the name says nothing
    by_name = classify(name)
    return by_name if by_name != 'Miscellaneous' else classify(heading)

def classify(n):
    n = n.upper()
    for pat, cat in [
        (r'BACK BAND', 'Back Band'), (r'CHAIR RAIL', 'Chair Rail'), (r'STOOL', 'Stool Cap'), (r'APRON', 'Apron'),
        (r'CASING', 'Window and Door Casing'), (r'CROWN|BED|COVE|CORNICE', 'Crown'), (r'BRICK', 'Brick Mould'),
        (r'SHOE|BASE MOULDING|BASE CAP', 'Shoe Moulding'), (r'\bBASE\b', 'Base Board and Base Cap'), (r'STOP', 'Window Stops'),
        (r'PANEL', 'Panel'), (r'\bBAND\b', 'Band'), (r'HAND RAIL', 'Hand Rail'), (r'ASTRAGAL', 'Astragal'), (r'\bCAP\b', 'Header Cap'),
    ]:
        if re.search(pat, n): return cat
    return 'Miscellaneous'

out = []
for num, s in sorted(shapes.items()):
    if 'ROSETTE' in s['name']: continue  # corner blocks, not lineal moulding
    pts = s['pts']
    xs = [p[0] for p in pts]; ys = [p[1] for p in pts]
    sw, sh = max(xs) - min(xs), max(ys) - min(ys)
    t, w = s['thickness'], s['width']
    if not s['angled']:
        # Snap the traced outline to the printed size
        tw, th = (t, w) if sw <= sh else (w, t)
        kx, ky = tw / sw, th / sh
        pts = [[round((x - min(xs)) * kx, 4), round((y - min(ys)) * ky, 4)] for x, y in pts]
        sw, sh = tw, th
    name = re.sub(r'\b(L?WM)\b.*$', '', s['name']).strip().title()
    out.append({'num': f'BR-{num}', 'code': num, 'supplier': 'brosco', 'name': name, **({'wm': s['wm']} if s['wm'] else {}),
                'category': category(s['name'], s.get('heading', '')), 't': t, 'w': w, 'prices': {}, 'shape': pts,
                'sw': round(sw, 4), 'sh': round(sh, 4), **({'angled': True} if s['angled'] else {})})
src = f"""// Generated by scripts/import-brosco.py from Brosco's stock moulding chart (BROSCO-Mldg-Chart.pdf,
// brosco.com, printed full scale). Shapes are traced from the drawings and snapped to the printed
// thickness x width; crowns drawn at their installed angle are marked angled. Brosco sells through
// dealers, so there are no list prices here: enter your price per foot on the Orders tab.
import type {{ AMProfile }} from './andersonMcquaid';

export interface BroscoProfile extends AMProfile {{ supplier: 'brosco'; code: string; name: string; wm?: string }}

export const broscoCatalog: BroscoProfile[] = {json.dumps(out, separators=(',', ':'))};
"""
open('src/model/brosco.ts', 'w').write(src)
from collections import Counter
print(len(out), 'Brosco profiles', Counter(p['category'] for p in out))
